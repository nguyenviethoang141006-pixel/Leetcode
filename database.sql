CREATE DATABASE quanly_mixue;
USE quanly_mixue;


-- CỬA HÀNG
CREATE TABLE CUAHANGS (
    CUAHANG_ID INT AUTO_INCREMENT PRIMARY KEY,
    CUAHANG_NAME VARCHAR(100) NOT NULL
);
-- NHÂN VIÊN
CREATE TABLE NHANVIENS ( 
    NHANVIEN_ID INT AUTO_INCREMENT PRIMARY KEY, 
    NHANVIEN_NAME VARCHAR(100) NOT NULL 
);

-- SẢN PHẨM
CREATE TABLE SANPHAMS (
    SANPHAM_ID INT AUTO_INCREMENT PRIMARY KEY,
    SANPHAM_NAME VARCHAR(150) NOT NULL,
    DONGIA DECIMAL(10,2) NOT NULL 
);

-- TOPPING
CREATE TABLE TOPPINGS (
    TOPPING_ID INT AUTO_INCREMENT PRIMARY KEY,
    TOPPING_NAME VARCHAR(150) NOT NULL,
    DONGIA DECIMAL(10,2) NOT NULL
);



-- HÓA ĐƠN
CREATE TABLE HOADONS (
    HOADON_ID INT AUTO_INCREMENT PRIMARY KEY,
    CUAHANG_ID INT,
    NHANVIEN_ID INT, 
    THOIGIANDATHANG DATETIME NOT NULL, 
    THOIGIANTRATIEN DATETIME,          
    SOLUONG INT DEFAULT 0, 
    TONGTIEN DECIMAL(10,2) DEFAULT 0.00,
    FOREIGN KEY (CUAHANG_ID) REFERENCES CUAHANGS(CUAHANG_ID),
    FOREIGN KEY (NHANVIEN_ID) REFERENCES NHANVIENS(NHANVIEN_ID) 
);

CREATE TABLE CHITIETHOADONS (
    HOADON_DETAIL_ID INT AUTO_INCREMENT PRIMARY KEY,
    HOADON_ID INT,
    SANPHAM_ID INT,
    SOLUONG INT NOT NULL,         
    SOTIEN DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (HOADON_ID) REFERENCES HOADONS(HOADON_ID),
    FOREIGN KEY (SANPHAM_ID) REFERENCES SANPHAMS(SANPHAM_ID)
);

CREATE TABLE CHITIET_TOPPINGS (
    CHITIET_TOPPING_ID INT AUTO_INCREMENT PRIMARY KEY,
    HOADON_DETAIL_ID INT,
    TOPPING_ID INT,
    SOLUONG INT DEFAULT 1,
    SOTIEN DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (HOADON_DETAIL_ID) REFERENCES CHITIETHOADONS(HOADON_DETAIL_ID) ON DELETE CASCADE,
    FOREIGN KEY (TOPPING_ID) REFERENCES TOPPINGS(TOPPING_ID)
);


